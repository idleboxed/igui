//! Display names only, not an emulator support list or a source of filter tabs.
/// Expand a known platform code to its display name, preserving unknown codes.
pub fn full_name(alias: &str) -> &str {
    match alias {
        "NES" | "FC" => "Nintendo Entertainment System",
        "FDS" => "Famicom Disk System",
        "GB" => "Nintendo Game Boy",
        "GBC" => "Nintendo Game Boy Color",
        "GBA" => "Nintendo Game Boy Advance",
        "MD" | "GEN" => "Sega Mega Drive / Genesis",
        "SMS" => "Sega Master System",
        "GG" => "Sega Game Gear",
        "SG" | "SG1000" => "Sega SG-1000",
        "MCD" | "SCD" | "SEGACD" => "Sega Mega-CD / Sega CD",
        "SNES" | "SFC" => "Super Nintendo Entertainment System",
        "PSX" | "PS1" => "Sony PlayStation",
        "PCE" | "TG16" => "PC Engine / TurboGrafx-16",
        "PCECD" => "PC Engine CD-ROM",
        "WS" => "Bandai WonderSwan",
        "WSC" => "Bandai WonderSwan Color",
        "A2600" | "ATARI2600" => "Atari 2600",
        "A5200" | "ATARI5200" => "Atari 5200",
        "A7800" | "ATARI7800" => "Atari 7800",
        "ARCADE" => "Arcade",
        "MAME" => "Arcade (MAME)",
        "FBA" => "Arcade (FinalBurn Alpha)",
        "FBNEO" => "Arcade (FinalBurn Neo)",
        "CPS1" => "Capcom Play System I",
        "CPS2" => "Capcom Play System II",
        "CPS3" => "Capcom Play System III",
        "NEOGEO" => "SNK Neo Geo",
        "DAPHNE" => "LaserDisc Arcade",
        "N64" => "Nintendo 64",
        "NDS" => "Nintendo DS",
        _ => alias,
    }
}
